/**
 * Builds skins.generated.css from the registries, so the stylesheet (which has
 * to be there before the first paint) can never drift from the TypeScript
 * (which the tests and the picker read). `npm run gen:skins -w @sanctum/frontend`
 * rewrites the file; skins.test.ts fails if the committed copy is stale.
 *
 * Selecting a room or material only ever flips an attribute on <html>. The
 * scene image lives in a custom property that body reads, and only the active
 * room's rule is in effect, so the browser requests exactly one scene file —
 * the viewport's own orientation — and never preloads the rest.
 */
import { CORNER_CSS_PX, MOBILE_BREAKPOINT_PX, ROOM_LIST, ROOMS, flippedCornerDataUri, type RoomDef, type SceneAsset } from './rooms';
import { BORDERED_PILLS, CHIPS, NAV_SURFACES, ROUTE_BARE, ROUTE_PANELS, FRAMED_ROUTE_PANELS, EDITOR_FIELDS, MATERIAL_LIST, MOUNT_BACKING_PX, MOUNT_PLATES, PLATES, CLEAR_COMPOSER_FIELD, ORNAMENT_SLOTS, materialVars, ornamentVariants, skinVars, HEDGEWITCH_SUBSTRATE, HEDGEWITCH_PAPER_PLATES, HEDGEWITCH_PAPER_OVERLAYS, hedgewitchPaperOf, type MaterialDef, type PlateDef } from './materials';
import type { Orientation } from './types';

const q = (u: string) => `url("${u}")`;

/** WebP with a JPEG fallback via image-set; a single url() when the room has only one format. */
export function sceneImageSet(s: SceneAsset): { plain: string; set: string | null } {
  const only = (s.jpeg ?? s.webp) as string;
  if (s.webp && s.jpeg) {
    return {
      plain: q(s.jpeg),
      set: `image-set(${q(s.webp)} type("image/webp"), ${q(s.jpeg)} type("image/jpeg"))`,
    };
  }
  return { plain: q(only), set: null };
}

function roomBlock(room: RoomDef, o: Orientation): string {
  const s = room[o];
  const sel = room.id === 'hedgewitch' ? ':root:not([data-room]), :root[data-room="hedgewitch"]' : `:root[data-room="${room.id}"]`;
  const { plain, set } = sceneImageSet(s);
  const wash = room.id === 'hedgewitch' ? 'linear-gradient(rgba(16, 26, 14, 0.42), rgba(16, 26, 14, 0.52)), ' : '';
  const lines: string[] = [];
  lines.push(`${sel} {`);
  lines.push(`  --skin-room-image: ${wash}${plain};`);
  lines.push(`  --skin-room-position: ${s.position};`);
  if (o === 'landscape') {
    lines.push(`  --skin-room-fallback: ${room.fallback};`);
    if (room.corners) {
      lines.push(`  --skin-corner-tl: ${q(room.corners.tl)};`);
      lines.push(`  --skin-corner-tr: ${room.cornersFlipped ? q(flippedCornerDataUri('tr')) : q(room.corners.tr)};`);
      lines.push(`  --skin-corner-br: ${room.cornersFlipped ? q(flippedCornerDataUri('br')) : q(room.corners.br)};`);
      lines.push(`  --skin-corner-bl: ${room.cornersFlipped ? q(flippedCornerDataUri('bl')) : q(room.corners.bl)};`);
    }
  }
  lines.push('}');
  let out = lines.join('\n');
  if (set) out += `\n@supports (background-image: image-set(${q('x.webp')} type("image/webp"))) {\n  ${sel} { --skin-room-image: ${set}; }\n}`;
  return out;
}

export function buildSkinsCss(): string {
  const out: string[] = [];
  out.push('/* GENERATED by packages/frontend/src/theme/skins-css.ts — do not edit by hand.');
  out.push('   Rewrite with: npm run gen:skins -w @sanctum/frontend */', '');

  out.push('/* ── materials: one complete palette each ── */');
  for (const m of MATERIAL_LIST) {
    if (!m.roles) continue;
    const vars = materialVars(m.roles);
    const tile = ROOMS[m.defaultRoom].corners ? ROOMS[m.defaultRoom].tile : null;
    out.push(`:root[data-material="${m.id}"] {`);
    out.push(`  color-scheme: ${m.scheme};`);
    for (const [k, v] of Object.entries(vars)) out.push(`  ${k}: ${v};`);
    if (tile) out.push(`  --skin-tile: ${q(tile)};`);
    for (const [k, v] of Object.entries(skinVars(m))) out.push(`  ${k}: ${v};`);
    if (m.mounted) out.push(`  --skin-mount-ring: 0 0 0 ${MOUNT_BACKING_PX}px var(--surface-chrome), 0 0 0 ${MOUNT_BACKING_PX + 1}px ${m.roles!.trim};`);
    out.push('}', '');
  }

  const mounted = MATERIAL_LIST.filter(m => m.mounted);
  if (mounted.length) {
    out.push('/* ── mounted materials: the primary plates sit in a dark backing with a brass edge (not in Extra readable) ── */');
    for (const m of mounted) {
      for (const [sel, drop] of MOUNT_PLATES) {
        out.push(`:root[data-material="${m.id}"]:not([data-readability="extra"]) ${sel} { box-shadow: var(--skin-mount-ring)${drop === 'none' ? '' : ', ' + drop}; }`);
      }
      // The slim backing and edge take 3px outside each plate: keep stacked messages from touching.
      out.push(`:root[data-material="${m.id}"]:not([data-readability="extra"]) .message { margin-top: ${MOUNT_BACKING_PX + 4}px; margin-bottom: ${MOUNT_BACKING_PX + 4}px; }`);
    }
    out.push('');
  }

  out.push(...platesCss());
  out.push(...flatCss());
  out.push(...restoredMaterialsCss());
  out.push(...hedgewitchPaperCss());
  out.push(...crispCss());
  out.push(...chipRadiusCss());
  out.push(...routePanelsCss());

  out.push('/* ── rooms: landscape, then portrait at or below the shell breakpoint ── */');
  for (const r of ROOM_LIST) out.push(roomBlock(r, 'landscape'), '');
  out.push(`@media (max-width: ${MOBILE_BREAKPOINT_PX}px) {`);
  for (const r of ROOM_LIST) out.push(roomBlock(r, 'portrait').split('\n').map(l => '  ' + l).join('\n'), '');
  out.push('}', '');

  out.push('/* ── frame geometry shared by every room ── */');
  out.push(':root {');
  out.push(`  --skin-corner-size: ${CORNER_CSS_PX}px;`);
  out.push('}', '');
  return out.join('\n');
}

/**
 * Crisp edges (step 4): every card, bubble, chip and pill has an opaque fill (the plate colours are solid in every material) and a 1px
 * edge at full strength in the trim, with or without decorations. Not in Extra readable, which keeps its own hard 2px edge. The edge
 * columns (rail, drawer, topbar, subnav) are navigation surfaces and are left to the plate rules. The decorated rules below re-state
 * the same edge for plates; these also hold when decorations are off.
 */
function crispCss(): string[] {
  const out: string[] = ['/* ── crisp edges: 1px, full-strength trim on every card, bubble, chip and pill (not in Extra readable) ── */'];
  const cards = PLATES.filter(p => !p.edge && p.selector !== '.chat-header'); // the chat header is a navigation surface (step 5)
  for (const m of MATERIAL_LIST.filter(m => m.roles)) {
    const on = `:root[data-material="${m.id}"]:not([data-readability="extra"])`;
    const bordered = cards.filter(p => p.border).map(p => p.selector);
    const unbordered = cards.filter(p => !p.border).map(p => p.selector);
    out.push(`${on} :is(${[...bordered, ...BORDERED_PILLS].join(', ')}) { border-color: var(--skin-trim); }`);
    out.push(`${on} :is(${unbordered.join(', ')}) { outline: 1px solid var(--skin-trim); outline-offset: -1px; }`);
    out.push(`${on} :is(${CHIPS.join(', ')}) { border: 1px solid var(--skin-trim); }`);
  }
  out.push('');
  return out;
}

/** Squared chips and pills (and Home's Open chat button) for the materials whose painted plates are nearly square. Not in Extra readable. */
function chipRadiusCss(): string[] {
  const out: string[] = [];
  for (const m of MATERIAL_LIST.filter(m => m.chipRadius !== null)) {
    out.push(`:root[data-material="${m.id}"]:not([data-readability="extra"]) :is(${CHIPS.join(', ')}) { border-radius: ${m.chipRadius}px; }`);
  }
  if (out.length) out.push('');
  return out;
}

/**
 * Step 5: the Files / Canvas / Command / Browser / Observatory routes no longer sit under an opaque lid (skins.css), so the panels that were
 * drawn as a faint wash for glass over the room get a plate: the chrome colour (the pair the routes' remapped ink is drawn for), the trim
 * edge, and the chrome substrate at its own veil/scale/blend where decorations are on. Hedgewitch has no lid and is left alone; Extra readable keeps its lid.
 */
function routePanelsCss(): string[] {
  const out: string[] = ['/* ── routes without a lid: the panels on them are plates, the page behind them is the room ── */'];
  const panels = ROUTE_PANELS.join(', ');
  for (const m of MATERIAL_LIST.filter(m => m.roles)) {
    const on = `:root[data-material="${m.id}"]:not([data-readability="extra"])`;
    out.push(`${on} :is(${panels}) { background-color: var(--surface-chrome); box-shadow: inset 0 0 0 1px var(--skin-trim); }`);
    out.push(`${on} :is(${ROUTE_BARE.join(', ')}) { background: transparent; }`);
    const veil = 'color-mix(in srgb, var(--surface-chrome) var(--skin-veil-chrome), transparent)';
    out.push(`${on}[data-surface-decor="on"] :is(${panels}) { background-image: linear-gradient(${veil}, ${veil}), var(--skin-tex-chrome, none); background-size: auto, var(--skin-tex-chrome-size); background-repeat: no-repeat, repeat; background-blend-mode: normal, ${m.texture?.chrome.blend ?? 'normal'}; }`);
    // Framed route panels wear the Home card's frame (fittings, rim, relief, its small radius) over the same chrome substrate.
    const framed = FRAMED_ROUTE_PANELS[m.id];
    const relief = m.texture?.relief;
    if (framed?.length && relief) {
      const f = `:root[data-material="${m.id}"][data-surface-decor="on"]:not([data-readability="extra"]) :is(${framed.join(', ')})`;
      const corners = ['tl', 'tr', 'br', 'bl'].map(c => `var(--skin-fitting-${c}, none)`);
      const radius = m.flat?.radius ?? PLATES.find(p => p.selector === '.home-card')!.radius; // flat materials (smoked copper) keep their own near-square card radius
      out.push(`${f} { --plate-corner: ${relief.cornerPx ?? 18}px; border-color: transparent; border-radius: ${radius}px; outline: 1px solid var(--skin-trim); outline-offset: -1px; box-shadow: var(--skin-plate-relief); background-origin: border-box; background-image: ${[...corners, `linear-gradient(${veil}, ${veil})`, 'var(--skin-tex-chrome, none)'].join(', ')}; background-position: 0 0, 100% 0, 100% 100%, 0 100%, 0 0, 0 0; background-size: ${corners.map(() => 'var(--plate-corner) var(--plate-corner)').join(', ')}, auto, var(--skin-tex-chrome-size); background-repeat: no-repeat, no-repeat, no-repeat, no-repeat, no-repeat, repeat; background-blend-mode: normal, normal, normal, normal, normal, ${m.texture?.chrome.blend ?? 'normal'}; }`);
      out.push(`@media (max-width: 768px) { ${f} { --plate-corner: ${relief.cornerMobilePx ?? relief.cornerPx ?? 18}px; } }`);
    }
  }
  out.push('');
  return out;
}

