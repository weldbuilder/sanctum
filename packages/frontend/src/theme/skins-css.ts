function platesCss(): string[] {
  const out: string[] = [];
  const all = PLATES.map(p => p.selector);
  const sel = (list: string[]) => `${ON} :is(${list.join(', ')})`;
  const px = (n: number) => `${n}px`;

  out.push('/* ── plates: every primary plate is framed in its trim metal, cornered with its room\'s four corner pieces and textured over its own opaque colour ──');
  out.push('   Layers, top to bottom: four corners, the leaf etching (where the room has one), the texture veil, the texture; the colour is underneath all of it.');
  out.push('   The veil is the plate colour at (1 - alpha), so the composite is opaque and the texture is exactly `alpha` strong. Not in Extra readable, not with decorations off. */');
  out.push(`${sel(all)} {`);
  out.push('  background-color: var(--plate-bg);');
  out.push('  background-image: var(--skin-corner-tl, none), var(--skin-corner-tr, none), var(--skin-corner-br, none), var(--skin-corner-bl, none), var(--skin-orn, none),');
  out.push('    linear-gradient(color-mix(in srgb, var(--plate-bg) var(--plate-veil), transparent), color-mix(in srgb, var(--plate-bg) var(--plate-veil), transparent)), var(--plate-tex, none);');
  out.push('  background-position: 0 0, 100% 0, 100% 100%, 0 100%, 0 100%, 0 0, 0 0;');
  out.push('  background-size: var(--plate-corner) var(--plate-corner), var(--plate-corner) var(--plate-corner), var(--plate-corner) var(--plate-corner), var(--plate-corner) var(--plate-corner), var(--plate-orn-size, 0 0), auto, var(--plate-tex-size);');
  out.push('  background-repeat: no-repeat, no-repeat, no-repeat, no-repeat, no-repeat, no-repeat, repeat;');
  out.push('  background-origin: border-box;');
  out.push('  background-clip: border-box;');
  out.push('  border-radius: var(--plate-radius);');
  out.push('}');

  for (const p of PLATES) out.push(plateRule(p));

  out.push('@media (max-width: 768px) {');
  for (const p of PLATES) if (p.cornerMobile !== p.corner) out.push(`  ${ON} ${p.selector} { --plate-corner: ${px(p.cornerMobile)}; }`);
  out.push('}', '');

  // A light material (the library) draws its sidebar and composer as dark chrome with the chrome ink.
  out.push('/* ── a light material draws these plates as dark chrome (the library: leather, brass), not as paper ── */');
  for (const m of MATERIAL_LIST.filter(m => m.roles && m.scheme === 'light')) {
    for (const p of PLATES.filter(p => p.chromeInLight)) {
      const s = `:root[data-material="${m.id}"][data-decor="on"] ${p.selector}`;
      out.push(`${s} { --plate-bg: var(--surface-chrome); --plate-tex: var(--skin-tex-chrome); --plate-veil: var(--skin-veil-chrome); --plate-tex-size: var(--skin-tex-chrome-size); box-shadow: ${p.drop}; ${CHROME_INK.map(([k, v]) => `${k}: ${v};`).join(' ')} }`);
    }
  }
  out.push('');

  out.push('/* ── the composer: a framed plate in the chrome, with the message field set into it ── */');
  out.push(`${ON} .composer-inner { padding: 0.5rem 0.6rem 0.5rem 0.6rem; --surface-input-text: var(--surface-chrome-text); --surface-input-placeholder: var(--surface-chrome-muted); --link: var(--surface-chrome-text); --bg-active: var(--chrome-hover-wash); --focus-ring: var(--focus-ring-chrome); }`);
  out.push(`${ON} .composer-textarea { background: var(--skin-field-bg); color: var(--skin-field-text); border-radius: 8px; padding: 0.4rem 0.8rem; box-shadow: inset 0 0 0 1px var(--control-border); }`);
  out.push(`${ON} .composer-textarea::placeholder { color: var(--skin-field-placeholder); }`);
  // The frame's 24px gutter already narrows a phone, so the field gives up some of its own padding.
  out.push(`@media (max-width: 768px) { ${ON} .composer-textarea { padding: 0.4rem 0.6rem; } ${ON} .composer-inner { gap: 0.3rem; } }`);
  out.push('');
  return out;
}

function plateRule(p: PlateDef, prefix = ON): string {
  const d: string[] = [];
  d.push(`--plate-bg: var(${p.surface})`);
  d.push(`--plate-tex: var(--skin-tex-${p.kind})`);
  d.push(`--plate-veil: var(--skin-veil-${p.kind})`);
  d.push(`--plate-tex-size: var(--skin-tex-${p.kind}-size)`);
  d.push(`--plate-corner: ${p.corner}px`);
  d.push(`--plate-radius: ${p.radius}px`);
  if (p.ornament) d.push('--plate-orn-size: var(--skin-orn-size, 0 0)');
  if (p.edge) d.push(`border-${p.edge}: 1px solid var(--skin-trim)`);
  else if (p.border) d.push('border-color: var(--skin-trim)');
  else d.push('outline: 1px solid var(--skin-trim)', 'outline-offset: -1px');
  return `${prefix} ${p.selector} { ${d.join('; ')}; }`;
}

/** Approved ornate materials own their complete background stack even when the room
 * has no decorative frame. No DOM/pseudo-element overlays, hit targets or content insets. */
function restoredMaterialsCss(): string[] {
  const out: string[] = [];
  for (const m of MATERIAL_LIST.filter(m => m.roles && m.texture?.relief && !m.flat)) {
    const t = m.texture!, r = m.roles!;
    const mat = `:root[data-material="${m.id}"]`;
    const on = `${mat}[data-surface-decor="on"]:not([data-readability="extra"])`;
    const list = `:is(${PLATES.map(p => p.selector).join(', ')})`;
    out.push(`/* ── ${m.id}: tactile substrate, local fittings and bounded edge art ── */`);
    out.push(`${on} { --skin-corner-tl: var(--skin-fitting-tl); --skin-corner-tr: var(--skin-fitting-tr); --skin-corner-br: var(--skin-fitting-br); --skin-corner-bl: var(--skin-fitting-bl); --skin-corner-size: 32px; }`);
    for (const p of PLATES) {
      out.push(plateRule(p, on));
      // A light material's navigation columns (chrome-coloured) wear the chrome substrate, never the paper over the dark chrome.
      const kind = p.selector === '.message.user' ? 'user' : p.selector === '.message.companion' && t.companion ? 'companion' : (p.chromeInLight || NAV_SURFACES.includes(p.selector)) && m.scheme === 'light' ? 'chrome' : p.kind;
      const ornament = t.ornament && ['.home-card', '.message.companion', '.message.user', '.thread-sidebar'].includes(p.selector);
      out.push(`${on} ${p.selector} { --plate-tex: var(--skin-tex-${kind}); --plate-veil: var(--skin-veil-${kind}); --plate-tex-size: var(--skin-tex-${kind}-size); --plate-blend: var(--skin-tex-${kind}-blend); --plate-corner: ${p.corner ? t.relief!.cornerPx : 0}px; --plate-orn-size: ${ornament ? 'var(--skin-orn-size)' : '0px'}; --plate-orn-position: var(--skin-orn-position, 0 100%); box-shadow: ${p.edge ? 'none' : 'var(--skin-plate-relief)'}; }`);
    }
    // Top-down order: worked hardware; non-repeating aged edges/etching; optional damask;
    // opacity veil; real tactile substrate; opaque material base. Damask is removed on velvet.
    const corners = ['tl', 'tr', 'br', 'bl'].map(c => `var(--skin-fitting-${c}, none)`);
    const edge = t.edge;
    const rgba = edge ? `color-mix(in srgb, ${edge.ink} ${edge.alpha * 100}%, transparent)` : '';
    const edgeLayers = edge ? ['bottom', 'left', 'top', 'right'].map(dir => `linear-gradient(to ${dir}, ${rgba}, transparent ${edge.widthPx}px)`) : [];
    const edgeSizes = edge ? [`100% ${edge.widthPx}px`, `${edge.widthPx}px 100%`, `100% ${edge.widthPx}px`, `${edge.widthPx}px 100%`] : [];
    const edgePositions = edge ? ['0 0', '100% 0', '0 100%', '0 0'] : [];
    const images = [...corners, ...edgeLayers, 'var(--skin-orn, none)', 'var(--plate-pattern, none)', 'linear-gradient(color-mix(in srgb, var(--plate-bg) var(--plate-veil), transparent), color-mix(in srgb, var(--plate-bg) var(--plate-veil), transparent))', 'var(--plate-tex, none)'];
    // the ornament keeps its size, but never taller than the plate (a one-line bubble, a collapsed card): then it shrinks, whole
    const sizes = [...corners.map(() => 'var(--plate-corner) var(--plate-corner)'), ...edgeSizes, 'auto min(var(--plate-orn-size), calc(100% - 8px))', 'var(--skin-pattern-size, auto)', 'auto', 'var(--plate-tex-size)'];
    const positions = ['0 0', '100% 0', '100% 100%', '0 100%', ...edgePositions, 'var(--plate-orn-position)', '0 0', '0 0', '0 0'];
    const repeats = images.map((_v, i) => i === images.length - 1 || i === images.length - 3 ? 'repeat' : 'no-repeat');
    const blends = images.map((_v, i) => i === images.length - 1 ? 'var(--plate-blend)' : 'normal');
    out.push(`${on} ${list} { background-color: var(--plate-bg); background-origin: border-box; background-clip: border-box; border-radius: var(--plate-radius); background-image: ${images.join(', ')}; background-position: ${positions.join(', ')}; background-size: ${sizes.join(', ')}; background-repeat: ${repeats.join(', ')}; background-blend-mode: ${blends.join(', ')}; }`);
    if (t.pattern) {
      out.push(`${on} ${list} { --plate-pattern: var(--skin-pattern); }`);
      if (t.user) out.push(`${on} .message.user { --plate-pattern: none; }`);
    }
    if (m.scheme === 'light') {
      for (const p of PLATES.filter(p => p.chromeInLight)) out.push(`${on} ${p.selector} { --plate-bg: var(--surface-chrome); ${CHROME_INK.map(([k, v]) => `${k}: ${v};`).join(' ')} }`);
      // The dark chrome plates keep their own rim (the Library's oxblood on its wood), not the paper's brass.
      if (t.relief?.chromeShadow) out.push(`${on} :is(${PLATES.filter(p => (p.kind === 'chrome' || p.chromeInLight) && !p.edge).map(p => p.selector).join(', ')}) { --skin-trim: var(--skin-chrome-trim); box-shadow: var(--skin-chrome-relief); }`);
      // Burnt edges belong to paper only; the Library chrome uses its leather and brass.
      const chrome = PLATES.filter(p => p.kind === 'chrome' || p.chromeInLight).map(p => p.selector).join(', ');
      out.push(`${on} :is(${chrome}) { background-image: ${[...corners, 'linear-gradient(color-mix(in srgb, var(--plate-bg) var(--plate-veil), transparent), color-mix(in srgb, var(--plate-bg) var(--plate-veil), transparent))', 'var(--plate-tex, none)'].join(', ')}; background-position: 0 0, 100% 0, 100% 100%, 0 100%, 0 0, 0 0; background-size: ${corners.map(() => 'var(--plate-corner) var(--plate-corner)').join(', ')}, auto, var(--plate-tex-size); background-repeat: no-repeat, no-repeat, no-repeat, no-repeat, no-repeat, repeat; background-blend-mode: normal, normal, normal, normal, normal, var(--plate-blend); }`);
    }
    // Accent plates (Moonlit Cloister's Home cards) wear the "You" colour and substrate, with the panel's own ink.
    const sub = m.accentSubstrate;
    if (m.accents.length) out.push(`${on} :is(${m.accents.join(', ')}) { --plate-bg: var(--surface-${sub}); --plate-tex: var(--skin-tex-${sub}); --plate-veil: var(--skin-veil-${sub}); --plate-tex-size: var(--skin-tex-${sub}-size); --plate-blend: var(--skin-tex-${sub}-blend); }`);
    // A menu in the "You" substrate (Crimson Velvet's velvet rail) marks its selected item in its own, brighter colour.
    const menu = m.accents.filter(a => NAV_SURFACES.includes(a));
    if (menu.length) out.push(`${on} :is(${menu.join(', ')}) { --surface-chrome-selected: ${r.accentSelected}; }`);
    if (t.ornament?.clearance) {
      const side = t.ornament.position?.startsWith('0 ') ? 'left' : 'right';
      const v = t.ornament.variants;
      const sideOf = (sel: string) => v?.rightPlates.includes(sel) ? 'right' : side;
      out.push(`${on} :is(.home-card, .message.companion, .message.user, .thread-sidebar) { --material-orn-clearance: var(--skin-orn-size); }`);
      out.push(`${on} .home-card { padding-${sideOf('.home-card')}: calc(1.2rem + var(--material-orn-clearance)); }`);
      for (const sel of ['.message.companion', '.message.user']) out.push(`${on} ${sel} { padding-${sideOf(sel)}: calc(1.1rem + var(--material-orn-clearance)); overflow-wrap: anywhere; }`);
      // The chat list keeps its art below its content (its full width stays for the chats' names); every control and focus
      // ring stays clear of it, without moving or rebuilding the navigation.
      out.push(`${on} .thread-sidebar { padding-bottom: calc(8px + var(--material-orn-clearance)); }`);
      if (v) {
        // Each plate's data-orn slot picks a variant (the files are the material block's variables): a painting, upright at the
        // bottom or hanging from the top, and (where the material alternates) on the plate's own side or the other one, the
        // reserved space moving with it. One rule per plate and slot (no :is() list, whose specificity would be its weightiest
        // member's), so the phone rules below win.
        const plates = ['.home-card', '.message.companion', '.message.user', '.thread-sidebar'];
        for (const p of plates.filter(p => sideOf(p) === 'right')) out.push(`${on} ${p} { --skin-orn: var(--skin-orn-0-right); --plate-orn-position: 100% 100%; }`);
        const variants = ornamentVariants(v);
        const pad: Record<string, string> = { '.home-card': '1.2rem', '.message.companion': '1.1rem', '.message.user': '1.1rem' };
        for (let k = 0; k < ORNAMENT_SLOTS; k++) {
          const i = k % variants.length, { top, flip } = variants[i];
          for (const p of Object.keys(pad)) {
            const base = sideOf(p), side = flip ? (base === 'right' ? 'left' : 'right') : base;
            const room = v.alternate ? ` padding-${side}: calc(${pad[p]} + var(--material-orn-clearance)); padding-${side === 'right' ? 'left' : 'right'}: ${pad[p]};` : '';
            out.push(`${on} ${p}[data-orn="${k}"] { --skin-orn: var(--skin-orn-${i}-${side}); --plate-orn-position: ${side === 'right' ? '100%' : '0'} ${top ? '0' : '100%'};${room} }`);
          }
          // a phone's Home cards keep their art at the bottom (that is the room they reserve), the same painting upright
          const homeBase = sideOf('.home-card'), home = flip ? (homeBase === 'right' ? 'left' : 'right') : homeBase;
          if (top || v.alternate) out.push(`@media (max-width: 768px) { ${on} .home-card[data-orn="${k}"] { --skin-orn: var(--skin-orn-${i}-upright-${home}); --plate-orn-position: ${home === 'right' ? '100% 100%' : '0 100%'};${v.alternate ? ' padding-left: 0.85rem; padding-right: 0.85rem;' : ''} } }`);
        }
      }
      out.push(`${on} .message-header { flex-wrap: wrap; }`);
      out.push(`${on} .message-role { max-width: 100%; overflow-wrap: anywhere; }`);
      // A last-companion footer can contain six actions, read-aloud and a date/time.
      // Let groups wrap inside the reserved content width; never shrink hit targets or text.
      out.push(`${on} :is(.ral-row, .msg-action-row) { flex-wrap: wrap; min-width: 0; max-width: 100%; }`);
      out.push(`${on} .msg-action-row { flex: 1 1 auto; }`);
      out.push(`${on} :is(.msg-action-btn, .ral-btn) { flex-shrink: 0; }`);
      out.push(`${on} .bubble-ts { white-space: normal; overflow-wrap: anywhere; min-width: 0; max-width: 100%; flex-shrink: 1; }`);

      out.push(`@media (max-width: 768px) { ${on} :is(.home-card, .message.companion, .message.user, .thread-sidebar) { --material-orn-clearance: var(--skin-orn-mobile-size); } }`);
      // On a phone every Home card reserves the bottom-local art vertically, rather than taking 40–48px from the width
      // (half-width Today/Notes titles, and the full-width cards' text, which would otherwise wrap into a narrow column).
      out.push(`@media (max-width: 768px) { ${on} .home-card { padding-left: 0.85rem; padding-right: 0.85rem; padding-bottom: calc(0.7rem + var(--material-orn-clearance)); } }`);
    }
    if (m.scheme === 'light') out.push(`${mat} .message.user { --text-secondary: var(--surface-user-text); --text-muted: var(--surface-user-text); }`);
    if (r.userDanger !== r.error) out.push(`${mat} .message.user .msg-action-btn.danger:hover { color: var(--surface-user-danger); }`);
    // These fields are material-owned in every readability/decor state, at rest/focus/blur.
    out.push(`${mat} .composer-textarea { --control-border: ${r.controlBorder}; --focus-ring: ${r.focus}; background-color: var(--skin-field-bg); color: var(--skin-field-text); caret-color: var(--skin-field-text); }`);
    out.push(`${mat} .composer-textarea::placeholder { color: var(--skin-field-placeholder); }`);
    const fields = `${mat} :is(${EDITOR_FIELDS.join(', ')})`;
    out.push(`${fields} { --control-border: ${r.controlBorder}; --focus-ring: ${r.focus}; background-color: var(--skin-editor-bg); background-image: none; color: var(--skin-editor-text); caret-color: var(--skin-editor-text); border: 1px solid var(--control-border); border-radius: 8px; box-shadow: none; padding: 2px 8px; }`);
    out.push(`${fields}::placeholder { color: var(--skin-editor-placeholder); }`);
    out.push(`${fields}:focus, ${fields}:focus-visible { outline: 2px solid var(--skin-editor-focus); outline-offset: -4px; border-color: var(--control-border); box-shadow: none; }`);
    out.push(`${mat}[data-readability="extra"] :is(${EDITOR_FIELDS.join(', ')}):focus-visible { outline-width: 3px; }`);
    out.push(`${on} .home-card::after { display: none; }`);
    // A one-surface chat bar (the Library's wood): the field inside it is clear, in the chrome's own ink.
    if (CLEAR_COMPOSER_FIELD.has(m.id)) {
      out.push(`${on} .composer-textarea { background-color: transparent; box-shadow: none; color: var(--surface-chrome-text); caret-color: var(--surface-chrome-text); }`);
      out.push(`${on} .composer-textarea::placeholder { color: var(--surface-chrome-muted); }`);
    }
    out.push(`${on} .skin-line { border-color: var(--skin-frame); box-shadow: var(--skin-frame-relief); }`);
    out.push(`@media (max-width: 768px) { ${on} ${list} { --plate-corner: ${t.relief!.cornerMobilePx}px; } ${on} :is(${PLATES.filter(p => !p.corner).map(p => p.selector).join(', ')}) { --plate-corner: 0px; } ${on} :is(.home-card, .message.companion, .message.user, .thread-sidebar) { --plate-orn-size: var(--skin-orn-mobile-size, 0px); } }`);
    out.push('');
  }
  return out;
}

/** Restrained material plates preserve their geometry and opaque material-owned fields.
 * Restored Ember replaces the shared motifs with fine leather and separate copper fittings;
 * hardware overrides room corners at higher specificity without touching the scenery. */
function flatCss(): string[] {
  const out: string[] = [];
  for (const m of MATERIAL_LIST.filter((m): m is MaterialDef & { flat: NonNullable<MaterialDef['flat']> } => !!m.flat && !!m.roles)) {
    const f = m.flat;
    const mat = `:root[data-material="${m.id}"]`;
    // one :not() more than the generic rules (whose :is() lists weigh as their most specific selector), so these win without relying on order
    const on = `${mat}[data-surface-decor="on"]:not([data-readability="extra"])`;
    const cols = PLATES.filter(p => p.edge);
    const cards = PLATES.filter(p => !p.edge);
    const chrome = PLATES.filter(p => p.kind === 'chrome' && !f.surfaces[p.selector]);
    const list = (ps: PlateDef[]) => `:is(${ps.map(p => p.selector).join(', ')})`;
    out.push(`/* ── ${m.id}: flat plates, one thin frame, material-owned active editors ── */`);
    out.push(`${mat} .message.user { --text-secondary: var(--surface-user-text); --text-muted: var(--surface-user-text); }`);
    // The room may have no frame: declare the material plate contract independently.
    for (const p of PLATES) out.push(plateRule({ ...p, ornament: false }, on));
    out.push(`${on} ${list(PLATES)} { background-color: var(--plate-bg); border-radius: var(--plate-radius); background-origin: border-box; background-clip: border-box; background-image: none; box-shadow: none; }`);
    out.push(`${on} ${list(cards)} { --plate-radius: ${f.radius}px; }`);
    out.push(`${on} ${list(cols)} { --plate-radius: 0px; }`);
    // The approved tactile treatment is independent of the scene and the old pack motifs.
    // Fittings, opaque colour veil and micrograin are distinct background layers; none can intercept input.
    if (m.texture?.relief) {
      out.push(`${on} { --skin-corner-tl: var(--skin-fitting-tl); --skin-corner-tr: var(--skin-fitting-tr); --skin-corner-br: var(--skin-fitting-br); --skin-corner-bl: var(--skin-fitting-bl); --skin-corner-size: 32px; }`);
      out.push(`${on} ${list(PLATES)} { background-image: var(--skin-fitting-tl, none), var(--skin-fitting-tr, none), var(--skin-fitting-br, none), var(--skin-fitting-bl, none), linear-gradient(color-mix(in srgb, var(--plate-bg) var(--plate-veil), transparent), color-mix(in srgb, var(--plate-bg) var(--plate-veil), transparent)), var(--plate-tex, none); background-position: 0 0, 100% 0, 100% 100%, 0 100%, 0 0, 0 0; background-size: var(--plate-corner) var(--plate-corner), var(--plate-corner) var(--plate-corner), var(--plate-corner) var(--plate-corner), var(--plate-corner) var(--plate-corner), auto, var(--plate-tex-size); background-repeat: no-repeat, no-repeat, no-repeat, no-repeat, no-repeat, repeat; background-blend-mode: normal, normal, normal, normal, normal, ${m.texture.card.blend ?? 'normal'}; --link: var(--amber-bright); --amber: var(--amber-bright); }`);
      out.push(`${on} ${list(cards)} { --plate-corner: ${m.texture.relief.cornerPx ?? 18}px; box-shadow: var(--skin-plate-relief); }`);
      out.push(`${on} ${list(cols)} { --plate-corner: 0px; }`);
      out.push(`@media (max-width: 768px) { ${on} ${list(cards)} { --plate-corner: ${m.texture.relief.cornerMobilePx ?? m.texture.relief.cornerPx ?? 18}px; } }`);
      // Soft plates (the bubbles and the input bar) are rounded and carry no fittings; after the rules above, so they win at every width.
      if (f.soft) out.push(`${on} :is(${f.soft.selectors.join(', ')}) { --plate-radius: ${f.soft.radius}px; --plate-corner: 0px; box-shadow: 0 2px 8px rgba(0, 0, 0, 0.35); }`);
      // A separate "You" substrate (Ember's navy leather) on the user's plate, never the companion's.
      if (m.texture.user) out.push(`${on} .message.user { --plate-tex: var(--skin-tex-user); --plate-veil: var(--skin-veil-user); --plate-tex-size: var(--skin-tex-user-size); }`);
      out.push(`${on} .home-card::after { display: none; }`);
      // The inset field also owns its pair when the selected room has no decorative frame.
      out.push(`${on} .composer-textarea { background-color: var(--skin-field-bg); color: var(--skin-field-text); border-radius: 8px; box-shadow: inset 0 0 0 1px var(--control-border); }`);
      out.push(`${on} .composer-textarea::placeholder { color: var(--skin-field-placeholder); }`);
    } else {
      out.push(`${on} ${list(chrome)} { background-image: linear-gradient(color-mix(in srgb, var(--plate-bg) var(--plate-veil), transparent), color-mix(in srgb, var(--plate-bg) var(--plate-veil), transparent)), var(--plate-tex, none); background-position: 0 0, 0 0; background-size: auto, var(--plate-tex-size); background-repeat: no-repeat, repeat; }`);
    }
    // Retained legacy override; restored Ember sets this to null and uses its bounded substrate.
    if (f.woodgrain) {
      const wood = [...cards.filter(p => p.kind === 'card' || f.surfaces[p.selector]), ...cols.filter(p => NAV_SURFACES.includes(p.selector))];
      const veil = `color-mix(in srgb, var(--plate-bg) ${Math.round((1 - f.woodgrain.opacity) * 100)}%, transparent)`;
      out.push(`${on} ${list(wood)} { background-image: linear-gradient(${veil}, ${veil}), ${q(f.woodgrain.url)}; background-position: 0 0, 0 0; background-size: auto, ${f.woodgrain.tilePx[0]}px ${f.woodgrain.tilePx[1]}px; background-repeat: no-repeat, repeat; }`);
    }
    for (const [sel, surf] of Object.entries(f.surfaces)) out.push(`${on} ${sel} { --plate-bg: var(${surf}); --plate-tex: var(--skin-tex-card); --plate-veil: var(--skin-veil-card); --plate-tex-size: var(--skin-tex-card-size); }`);
    // Accent plates (Ember's Home cards) wear the "You" colour and leather, with the panel's own ink.
    if (m.accents.length && m.texture?.user) out.push(`${on} :is(${m.accents.join(', ')}) { --plate-bg: var(--surface-user); --plate-tex: var(--skin-tex-user); --plate-veil: var(--skin-veil-user); --plate-tex-size: var(--skin-tex-user-size); }`);
    // A composer with its own leather (Ember's black) is the field itself: the message field inside it is clear, never an inset
    // (ivory or otherwise), and the placeholder and resting icons take the quiet ink lifted for that leather.
    if (m.texture?.composer) {
      out.push(`${on} .composer-inner { --plate-tex: var(--skin-tex-composer); --plate-veil: var(--skin-veil-composer); --plate-tex-size: var(--skin-tex-composer-size); --surface-input-placeholder: var(--composer-muted); --surface-chrome-muted: var(--composer-muted); --text-muted: var(--composer-muted); }`);
      out.push(`${on} .composer-textarea { background-color: transparent; box-shadow: none; }`);
      out.push(`${on} .composer-textarea::placeholder { color: var(--composer-muted); }`);
    }
    for (const sel of f.quiet) out.push(`${on} ${sel} { border-color: var(--skin-trim-quiet); }`);
    out.push(`${on} .skin-ring-wash, ${on} .skin-ring-tile { display: none; }`);
    out.push(`${on} .skin-line { inset: 0; border-color: var(--skin-frame); box-shadow: ${m.texture?.relief ? 'var(--skin-frame-relief)' : 'none'}; }`);
    for (const sel of f.primary) {
      out.push(`${mat} ${sel} { background: var(--control-primary-bg); color: var(--control-primary-text); border-color: var(--control-primary-bg); }`);
      out.push(`${mat} ${sel}:hover { background: var(--control-primary-hover); color: var(--control-primary-text); border-color: var(--control-primary-hover); }`);
    }
    if (m.roles!.editor) {
      const sel = `${mat} :is(${EDITOR_FIELDS.join(', ')})`;
      out.push(`${sel} { background-color: var(--skin-editor-bg); color: var(--skin-editor-text); caret-color: var(--skin-editor-text); border: 1px solid var(--skin-editor-text); border-radius: 8px; box-shadow: none; padding: 2px 8px; }`);
      out.push(`${on} :is(${EDITOR_FIELDS.join(', ')}) { background-image: var(--skin-editor-tex); background-size: var(--skin-editor-tex-size); background-repeat: repeat; }`);
      out.push(`${sel}::placeholder { color: var(--skin-editor-placeholder); }`);
      // The ring sits inside the opaque editor surface, in the material's own focus colour.
      // the padding above keeps the inset ring clear of the first letter (the rename field ships with padding 0), and it is set at rest so nothing moves on focus
      out.push(`${sel}:focus, ${sel}:focus-visible { outline: 2px solid var(--skin-editor-focus); outline-offset: -4px; border-color: var(--skin-editor-text); box-shadow: none; }`);
      // the slash popup's selected row carries an amber wash under the copper command name: give the name the popover ink there
      out.push(`${mat} .slash-item-sel .slash-name, ${mat} .slash-item-sel .slash-enter { color: var(--surface-popover-text); }`);
    }
    out.push('');
  }
  return out;
}


/** Fine paper on the existing warm legacy plates. Plants use the existing Home hook; no DOM/padding changes. */
